# Build fig1.plt (JASA Fig. 1) from a box model, one source of geometry.
# Sizing: absolute cap heights so that at double-column width (6.69 in) the
# printed lettering is ~9 pt (>= AIP 8 pt minimum). Subtitles shortened so
# they fit the boxes at that size.
TITLE_H = 0.121   # uniform cap height; titles are bold for emphasis
SUB_H = 0.121

BOXES = [
    ("Stapes",         ["acoustic", "drive"],            False),
    ("Traveling wave", ["fluid-coupled line", "2.75 decades"], False),
    ("3-DOF section",  ["BM + RL + TM", "shear-path filter"], True),
    ("IHC gate",       ["first order,", "bounded"],        False),
    ("Neural",         ["output"],                        False),
]
x0 = 0.10
gap = 0.30
W = [1.25, 2.15, 2.05, 1.62, 1.15]
ytop, ybot = 2.55, 1.30
ymid = (ytop + ybot) / 2
xs = []
x = x0
for w in W:
    xs.append((x, x + w)); x += w + gap
cx = [(a + b) / 2 for a, b in xs]
XMAX = xs[-1][1] + 0.12
YMAX = 3.55

L = []
L += ["; fig1.plt - JASA Fig. 1 in PLT",
      "; Structure of the model family: signal path with OHC feedback.",
      "; 3-DOF section (the paper's subject) carries a heavier outline;",
      "; main-path boxes blue, OHC feedback box red. Generated by mkfig1.py.",
      "; Lettering caption-size at double-column width (6.69 in).",
      ";",
      "head=0 : clip=0",
      "xllc=0.15 : yllc=0.45 : xlen=%.2f : ylen=%.2f" % (XMAX, YMAX),
      "xmin=0 : xmax=%.2f : ymin=0 : ymax=%.2f" % (XMAX, YMAX),
      "xaxis=0 : yaxis=0 : taxis=0 : raxis=0",
      ""]
# main boxes (all but 3-DOF), blue thin
L += ["; main signal-path boxes (blue outlines)", "pltcol=1 : pltlwt=1.5 : pltype=rect"]
for i, (a, b) in enumerate(xs):
    if BOXES[i][2]:
        continue
    L += ["%.3f %.2f" % (a, ybot), "%.3f %.2f" % (b, ytop), "plot"]
# 3-DOF box, heavier
i3 = [i for i, B in enumerate(BOXES) if B[2]][0]
a, b = xs[i3]
L += ["; 3-DOF section box, heavier outline", "pltlwt=3",
      "%.3f %.2f" % (a, ybot), "%.3f %.2f" % (b, ytop), "plot", ""]
# OHC feedback box (red) below 3-DOF
fb = (a - 0.02, b + 0.02); fy0, fy1 = 0.08, 1.05
L += ["; OHC feedback box (red)", "pltcol=4 : pltlwt=1.5",
      "%.3f %.2f" % (fb[0], fy0), "%.3f %.2f" % (fb[1], fy1), "plot", ""]
# signal-path arrows (black)
L += ["; signal-path arrows (black)",
      "pltype=lines : aronum=1 : arosiz=1.2 : pltcol=0 : pltlwt=1.5"]
for i in range(len(xs) - 1):
    L += ["%.3f %.3f" % (xs[i][1], ymid), "%.3f %.3f" % (xs[i + 1][0], ymid), "plot"]
L.append("")
# observable arrows (blue) from 3-DOF and Neural
L += ["; observable arrows (blue, up)", "pltcol=1"]
L += ["%.3f %.2f" % (cx[i3], ytop), "%.3f %.2f" % (cx[i3], ytop + 0.55), "plot"]
L += ["%.3f %.2f" % (cx[4], ytop), "%.3f %.2f" % (cx[4], ytop + 0.55), "plot", ""]
# feedback arrows (red) up into 3-DOF
fa1, fa2 = a + 0.60, b - 0.60
L += ["; feedback arrows (red, up)", "pltcol=4"]
L += ["%.3f %.2f" % (fa1, fy1), "%.3f %.2f" % (fa1, ybot), "plot"]
L += ["%.3f %.2f" % (fa2, fy1), "%.3f %.2f" % (fa2, ybot), "plot", "aronum=0", ""]
# text
L += ["; text", "msgdat=yes : mhal=cen : mval=half"]
ytitle = ytop - 0.30
ysub1 = ymid + 0.03
ysub2 = ymid - 0.27
L += ["msgcol=0 : msgsiz=-%.3f : msglwt=1.8" % TITLE_H]
for i, B in enumerate(BOXES):
    L.append('%.3f %.3f "%s"' % (cx[i], ytitle, B[0]))
L += ["msgcol=8 : msgsiz=-%.3f : msglwt=1" % SUB_H]
for i, B in enumerate(BOXES):
    subs = B[1]
    if len(subs) == 2:
        L.append('%.3f %.3f "%s"' % (cx[i], ysub1, subs[0]))
        L.append('%.3f %.3f "%s"' % (cx[i], ysub2, subs[1]))
    else:
        L.append('%.3f %.3f "%s"' % (cx[i], ymid - 0.12, subs[0]))
# OHC feedback text
fbx = (fb[0] + fb[1]) / 2
L += ["msgcol=0 : msgsiz=-%.3f : msglwt=1.8" % TITLE_H, '%.3f 0.78 "OHC feedback"' % fbx,
      "msgcol=8 : msgsiz=-%.3f : msglwt=1" % SUB_H,
      '%.3f 0.50 "saturating force at"' % fbx,
      '%.3f 0.26 "^g^ of local critical"' % fbx]
# observable labels (blue)
L += ["msgcol=1 : msgsiz=-%.3f : msglwt=1 : mhal=cen" % SUB_H,
      '%.3f %.3f "BM, RL observables"' % (cx[i3], ytop + 0.72),
      "mhal=rig",
      '%.3f %.3f "neural observable"' % (xs[4][1] + 0.05, ytop + 0.72)]
open('fig1.plt', 'w').write('\n'.join(L) + '\n')
print("fig1: natural width %.2f in, neural center %.2f" % (XMAX, cx[4]))
